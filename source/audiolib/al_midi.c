/* The AL_MIDI voice record at 0x248108, 40 bytes each. */
typedef struct alvoice {
    struct alvoice *next, *prev;
    int num;
    int key;
    int velocity;
    int channel;
    int pitchleft, pitchright; /* the A0/B0 value each bank got, without key-on */
    int timbre;
    int status; /* 0x2000 while the key is down: B0 bit 5 */
} alvoice;

/* The 48-byte channel record at 0x248270. Two more fields are kept by the
   exe but never matter: controller 94 is stored and never read, and a key
   offset that is only ever reset to 0 is added to every note. */
typedef struct {
    alvoice *head, *tail;
    int timbre;
    int pitchbend;
    int keyoffset; /* semitones from the bend */
    int keydetune; /* 1/32 semitones from the bend */
    int volume;
    int pan;
    int velocityoffset; /* reset to 0 and never set */
} alchannel;

