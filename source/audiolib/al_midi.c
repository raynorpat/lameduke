/* 0x70AB0 with the port choice made: bank 0 is the card's base port (or
   0x388), bank 1 is base + 2. */
static void send(int bank, int reg, int data)
{
    OPL_Write((bank << 8) | reg, data & 0xFF);
}

/* Write reg to bank 0 and, on a stereo card, to bank 1 too. */
static void sendboth(int reg, int data)
{
    if (stereo)
        send(0, reg, data);
    send(stereo ? 1 : 0, reg, data);
}

static void addtail(alvoice *v, alvoice **head, alvoice **tail)
{
    v->next = NULL;
    v->prev = *tail;
    if (*tail)
        (*tail)->next = v;
    else
        *head = v;
    *tail = v;
}

static void unlink_voice(alvoice *v, alvoice **head, alvoice **tail)
{
    if (v->prev)
        v->prev->next = v->next;
    else
        *head = v->next;
    if (v->next)
        v->next->prev = v->prev;
    else
        *tail = v->prev;
    v->next = v->prev = NULL;
}

/* 0x70B24: load the voice's timbre into its operators, if it changed. */
static void settimbre(int voice)
{
    alvoice *v = &voices[voice];
    const unsigned char *t;
    int timbre, mod, car;

    if (v->channel == PERCUSSION)
        timbre = percussion[v->key][0];
    else
        timbre = channels[v->channel].timbre;
    if (timbre == v->timbre)
        return;
    v->timbre = timbre;
    t = timbres[timbre];
    mod = voiceops[voice][0];
    car = voiceops[voice][1];
    opvolume[mod] = 63 - (t[2] & 0x3F);
    opksl[mod] = t[2] & 0xC0;
    sendboth(0xA0 + voice, 0);
    sendboth(0xB0 + voice, 0);
    sendboth(0x80 + opoffset[mod], 0xFF);
    sendboth(0x60 + opoffset[mod], t[4]);
    sendboth(0x80 + opoffset[mod], t[6]);
    sendboth(0x20 + opoffset[mod], t[0]);
    sendboth(0xE0 + opoffset[mod], t[8]);
    sendboth(0x40 + opoffset[mod], t[2]);
    if (opl3) {
        send(0, 0xC0 + voice, (t[10] & 0x0F) | 0x20);
        send(1, 0xC0 + voice, (t[10] & 0x0F) | 0x10);
    } else {
        send(0, 0xC0 + voice, t[10]);
    }
    opvolume[car] = 63 - (t[3] & 0x3F);
    opksl[car] = t[3] & 0xC0;
    sendboth(0x40 + opoffset[car], 0x3F);
    sendboth(0x80 + opoffset[car], 0xFF);
    sendboth(0x60 + opoffset[car], t[5]);
    sendboth(0x80 + opoffset[car], t[7]);
    sendboth(0x20 + opoffset[car], t[1]);
    sendboth(0xE0 + opoffset[car], t[9]);
}

/* 0x70F7C: the carrier level from timbre, velocity and channel volume, and
   on a stereo card the pan split. The velocity is clamped up to 127, so
   every note plays as if struck at 127. */
static void setvoicevolume(int voice)
{
    alvoice *v = &voices[voice];
    alchannel *c = &channels[v->channel];
    int car = voiceops[voice][1], vel = v->velocity + c->velocityoffset;
    unsigned vol, l, r;

    if (vel <= 127)
        vel = 127;
    vol = ((unsigned)opvolume[car] * (unsigned)(vel + 128) * (unsigned)c->volume) >> 15;
    if (!stereo) {
        send(0, 0x40 + opoffset[car], (int)(vol ^ 0x3F) | opksl[car]);
        return;
    }
    l = c->pan < 64 ? ((unsigned)c->pan * vol) >> 6 : vol;
    send(0, 0x40 + opoffset[car], (int)((l ^ 0x3F) & 0xFF) | opksl[car]);
    r = c->pan > 64 ? ((unsigned)(127 - c->pan) * vol) >> 6 : vol;
    send(1, 0x40 + opoffset[car], (int)((r ^ 0x3F) & 0xFF) | opksl[car]);
}

/* 0x71108: the note's F-number and block. The second bank plays 5/32 of a
   semitone sharp, except percussion. */
static void setvoicepitch(int voice)
{
    alvoice *v = &voices[voice];
    alchannel *c = &channels[v->channel];
    int note = (v->channel == PERCUSSION ? percussion[v->key][1] : v->key) + c->keyoffset - 12;
    int detune = c->keydetune, step, octave, pitch;

    if (note > 95)
        note = 95;
    if (note < 0)
        note = 0;
    octave = noteoctave[note];
    step = notestep[note];
    pitch = notefreq[detune][step] | octavebits[octave];
    v->pitchleft = pitch;
    pitch |= v->status;
    if (!stereo) {
        send(0, 0xA0 + voice, pitch);
        send(0, 0xB0 + voice, pitch >> 8);
        return;
    }
    send(0, 0xA0 + voice, pitch);
    send(0, 0xB0 + voice, pitch >> 8);
    if (v->channel != PERCUSSION)
        detune += 5;
    if (detune > 31) {
        detune -= 32;
        if (note < 95) {
            step = notestep[note + 1];
            octave = noteoctave[note + 1];
        }
    }
    pitch = notefreq[detune][step] | octavebits[octave];
    v->pitchright = pitch;
    pitch |= v->status;
    send(1, 0xA0 + voice, pitch);
    send(1, 0xB0 + voice, pitch >> 8);
}

/* 0x716F8 */
void AL_NoteOff(int channel, int key, int velocity)
{
    alvoice *v;

    (void)velocity;
    if (channel > PERCUSSION)
        return;
    for (v = channels[channel].head; v; v = v->next)
        if (v->key == key)
            break;
    if (!v)
        return;
    v->status = 0;
    if (stereo) {
        send(0, 0xB0 + v->num, v->pitchleft >> 8);
        send(1, 0xB0 + v->num, v->pitchright >> 8);
    } else {
        send(0, 0xB0 + v->num, v->pitchleft >> 8);
    }
    unlink_voice(v, &channels[channel].head, &channels[channel].tail);
    addtail(v, &free_head, &free_tail);
}

/* 0x71094 */
static alvoice *allocvoice(void)
{
    alvoice *v = free_head;

    if (v)
        unlink_voice(v, &free_head, &free_tail);
    return v;
}

/* 0x717EC: with every voice busy, a percussion note gives up its voice. */
void AL_NoteOn(int channel, int key, int velocity)
{
    alvoice *v;

    if (channel > PERCUSSION)
        return;
    if (velocity == 0) {
        AL_NoteOff(channel, key, 0);
        return;
    }
    v = allocvoice();
    if (!v && channels[PERCUSSION].head) {
        AL_NoteOff(PERCUSSION, channels[PERCUSSION].head->key, 0);
        v = allocvoice();
    }
    if (!v)
        return;
    v->key = key;
    v->channel = channel;
    v->velocity = velocity;
    v->status = 0x2000;
    addtail(v, &channels[channel].head, &channels[channel].tail);
    settimbre(v->num);
    setvoicevolume(v->num);
    setvoicepitch(v->num);
}

/* 0x71344: free every voice and reset every channel. Nothing is keyed off. */
static void resetvoices(void)
{
    int i;

    free_head = free_tail = NULL;
    pitchbendrange = 2;
    for (i = 0; i < NUMVOICES; i++) {
        voices[i].num = i;
        voices[i].key = 0;
        voices[i].velocity = 0;
        voices[i].channel = -1;
        voices[i].timbre = -1;
        voices[i].status = 0;
        addtail(&voices[i], &free_head, &free_tail);
    }
    for (i = 0; i < NUMCHANNELS; i++) {
        channels[i].head = channels[i].tail = NULL;
        channels[i].timbre = 0;
        channels[i].pitchbend = 0;
        channels[i].keyoffset = 0;
        channels[i].keydetune = 0;
        channels[i].volume = 90;
        channels[i].pan = 64;
        channels[i].velocityoffset = 0;
    }
}

/* 0x712D4 */
static void setchannelvolume(int channel, int volume)
{
    alvoice *v;

    channels[channel].volume = volume < 0 ? 0 : volume > 127 ? 127 : volume;
    for (v = channels[channel].head; v; v = v->next)
        setvoicevolume(v->num);
}

/* 0x718F8: volume, pan, reset controllers and all notes off. */
void AL_ControlChange(int channel, int type, int data)
{
    if (channel > PERCUSSION)
        return;
    switch (type) {
    case 7:
        setchannelvolume(channel, data);
        break;
    case 10:
        if (channel != PERCUSSION)
            channels[channel].pan = data;
        break;
    case 121:
        resetvoices();
        setchannelvolume(channel, 90);
        if (channel != PERCUSSION)
            channels[channel].pan = 64;
        break;
    case 123:
        while (channels[channel].head)
            AL_NoteOff(channel, channels[channel].head->key, 0);
        break;
    }
}

/* 0x719CC */
void AL_ProgramChange(int channel, int patch)
{
    if (channel <= PERCUSSION)
        channels[channel].timbre = patch;
}

/* 0x719E8: the 14-bit bend is lsb + msb * 256, as the exe reads it. */
void AL_SetPitchBend(int channel, int lsb, int msb)
{
    alchannel *c;
    alvoice *v;
    unsigned bend;

    if (channel > PERCUSSION)
        return;
    c = &channels[channel];
    c->pitchbend = lsb + (msb << 8);
    bend = (unsigned)c->pitchbend * (unsigned)pitchbendrange;
    c->keyoffset = (int)(bend >> 14) - pitchbendrange;
    c->keydetune = (int)(bend >> 9) & 31;
    for (v = c->head; v; v = v->next)
        setvoicepitch(v->num);
}

/* 0x71424: 32 steps of 1/32 semitone above each base F-number. */
static void calcfreqtable(void)
{
    int n, d, i;

    for (n = 0; n <= 95; n++) {
        notestep[n] = n % 12;
        noteoctave[n] = n / 12;
    }
    for (i = 0; i < 12; i++)
        notefreq[0][i] = basefreq[i];
    for (d = 1; d <= 31; d++) {
        double scale = pow(2.0, d * (1.0 / 384.0));

        for (i = 0; i < 12; i++)
            notefreq[d][i] = (int)(basefreq[i] * scale);
    }
}

/* 0x7156C with 0x714D0 for each bank. */
static void resetchip(void)
{
    int b, v;

    send(0, 0x01, 0x20);
    send(0, 0x08, 0);
    send(0, 0xBD, 0);
    if (opl3)
        send(1, 0x05, 1);
    for (b = 0; b < (stereo ? 2 : 1); b++) {
        for (v = 0; v < NUMVOICES; v++) {
            send(b, 0xA0 + v, 0);
            send(b, 0xB0 + v, 0);
            send(b, 0xE0 + opoffset[voiceops[v][0]], 0);
            send(b, 0xE0 + opoffset[voiceops[v][1]], 0);
        }
    }
}

/* 0x71C74. A Sound Blaster is taken to be an SB16, whose OPL3 AL_MIDI
   drives as a stereo pair of banks, as it does the PAS cards; an AdLib is
   one mono OPL2. */
int AL_Init(int card)
{
    OPL_Reset();
    stereo = opl3 = card != 3;
    calcfreqtable();
    resetvoices();
    resetchip();
    return 0;
}
